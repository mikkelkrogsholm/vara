    #[test]
    fn simultaneous_submits_are_idempotent_and_survive_reopen() {
        let dir = tempfile::tempdir_in(".").unwrap();
        let source = dir.path().join("fixture.wav");
        std::fs::write(&source, b"not audio").unwrap();
        let service = Files::new(host(), dir.path().to_path_buf()).unwrap();
        assert!(Files::new(host(), dir.path().to_path_buf()).is_err());
        let settings = Settings::default();
        let req = SubmitRequest {
            source: source.clone(),
            engine_id: Some("openai.speech".into()),
            language: Some("da".into()),
            request_id: Some("request-1".into()),
            diarize: false,
            speakers: None,
        };
        let barrier = Arc::new(std::sync::Barrier::new(8));
        let threads: Vec<_> = (0..8)
            .map(|_| {
                let svc = service.clone();
                let b = barrier.clone();
                let r = req.clone();
                let s = settings.clone();
                std::thread::spawn(move || {
                    b.wait();
                    svc.submit(r, &s).unwrap().job_id
                })
            })
            .collect();
        let ids: Vec<_> = threads.into_iter().map(|t| t.join().unwrap()).collect();
        assert!(ids.iter().all(|id| id == &ids[0]));
        let absolute = std::path::absolute(&source).unwrap();
        assert_eq!(
            service.status(&ids[0]).unwrap().source_path,
            absolute.to_str().unwrap()
        );
        let mut equivalent = req.clone();
        equivalent.source = absolute;
        assert_eq!(
            service.submit(equivalent, &settings).unwrap().job_id,
            ids[0]
        );
        assert_eq!(std::fs::read(&source).unwrap(), b"not audio");
        let mut changed_path = req.clone();
        changed_path.source = source.with_file_name("different.wav");
        assert_eq!(
            UserMessage::decode(&service.submit(changed_path, &settings).unwrap_err())
                .unwrap()
                .code,
            "file.request_conflict"
        );
        let mut changed = req.clone();
        changed.language = Some("en".into());
        assert_eq!(
            UserMessage::decode(&service.submit(changed, &settings).unwrap_err())
                .unwrap()
                .code,
            "file.request_conflict"
        );
        assert_eq!(service.inner.lock().documents.len(), 1);
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(10);
        while service.inner.lock().worker {
            assert!(std::time::Instant::now() < deadline);
            std::thread::yield_now();
        }
        drop(service);
        std::fs::remove_file(&source).unwrap();
        // The worker holds its Arc until the thread exits; allow it to release the profile lock.
        let reopened = loop {
            match Files::new(host(), dir.path().to_path_buf()) {
                Ok(s) => break s,
                Err(_) => {
                    assert!(std::time::Instant::now() < deadline);
                    std::thread::yield_now();
                }
            }
        };
        assert_eq!(reopened.submit(req, &settings).unwrap().job_id, ids[0]);
        assert_eq!(reopened.status(&ids[0]).unwrap().stage, FileStage::Failed);
        assert!(reopened.result(&ids[0]).is_err());
    }
