//! Durable file jobs. Never focus, paste, or use dictation recovery/audio retention.
#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]
pub struct SubmitRequest {
    pub source: PathBuf,
    pub engine_id: Option<String>,
    pub language: Option<String>,
    pub request_id: Option<String>,
    #[serde(default)]
    pub diarize: bool,
    #[serde(default)]
    pub speakers: Option<u32>,
}
#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]
pub struct JobReceipt {
    pub job_id: String,
}
pub struct Host {
    pub resource_dir: Option<std::path::PathBuf>,
    pub secret: Box<dyn Fn(&vara_core::EngineConfig) -> Result<Option<String>> + Send + Sync>,
    pub notify: Box<dyn Fn(Option<String>) + Send + Sync>,
}
fn host_message(code: &str) -> String {
    vara_core::UserMessage::new(code).wire()
}
fn host_wrapped(code: &str, cause: &str) -> String {
    let mut m = vara_core::UserMessage::new(code);
    if let Some(c) = vara_core::UserMessage::decode(cause) {
        m = m.caused_by(c);
    }
    m.wire()
}
fn host_io(code: &str, e: &std::io::Error) -> String {
    vara_core::UserMessage::new(code)
        .caused_by(vara_core::UserMessage::io_cause(e))
        .wire()
}
fn host_json(code: &str, e: &serde_json::Error) -> String {
    vara_core::UserMessage::new(code)
        .caused_by(
            vara_core::UserMessage::new("storage.json_location")
                .number("line", e.line() as i64)
                .number("column", e.column() as i64),
        )
        .wire()
}
fn now() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs() as i64
}

