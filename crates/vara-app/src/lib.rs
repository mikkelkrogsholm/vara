type Result<T> = std::result::Result<T, String>;
pub fn safe_error(raw: &str) -> String {
    fn filter(
        message: vara_core::UserMessage,
        catalog: &Value,
        depth: usize,
    ) -> Option<vara_core::UserMessage> {
        if depth >= 6 {
            return None;
        }
        let entry = catalog.get(&message.code)?;
        let mut clean = vara_core::UserMessage::new(&message.code);
        for (key, value) in message.params {
            let placeholder = format!("{{{key}}}");
            if entry
                .get("da")
                .and_then(Value::as_str)
                .is_some_and(|s| s.contains(&placeholder))
                || entry
                    .get("en")
                    .and_then(Value::as_str)
                    .is_some_and(|s| s.contains(&placeholder))
            {
                clean.params.insert(key, value);
            }
        }
        clean.cause = message
            .cause
            .and_then(|cause| filter(*cause, catalog, depth + 1).map(Box::new));
        Some(clean)
    }
    let sanitized = vara_core::UserMessage::decode(raw)
        .and_then(|m| {
            let catalog: Value = serde_json::from_str(vara_core::message::CATALOG).ok()?;
            filter(m, &catalog, 0)
        })
        .unwrap_or_else(|| vara_core::UserMessage::new("backend.operation_failed"));
    sanitized.wire()
}
// Preserve document text, but never return legacy free-form provider errors.
pub fn sanitize(value: &mut Value) {
    match value {
        Value::Object(map) => {
            // A saved historical engine may contain a credential-bearing URL.
            // Clients only need its identity/provenance; URLs stay in the host.
            if map.contains_key("provider")
                && map.contains_key("model")
                && map.contains_key("endpoint")
            {
                map.insert("endpoint".into(), Value::Null);
            }
            for (key, v) in map.iter_mut() {
                if (key == "error" || key == "diarization_error") && v.is_string() {
                    *v = Value::String(safe_error(v.as_str().unwrap()));
                } else {
                    sanitize(v);
                }
            }
        }
        Value::Array(items) => {
            for v in items {
                sanitize(v);
            }
        }
        _ => {}
    }
}
// Track provenance only for names generated by this version. A legacy name,
// even one that looks like a default, is always treated as user content.
fn add_who_speaker_defaults(document: &mut TranscriptionDocument, turns: &[SpeakerTurn]) {
    for turn in turns {
        if turn.speaker == "who-uncertain" || document.speakers.contains_key(&turn.speaker) {
            continue;
        }
        let ordinal = turn
            .speaker
            .strip_prefix("who-")
            .and_then(|n| n.parse::<u32>().ok())
            .unwrap_or(0)
            + 1;
        document
            .speakers
            .insert(turn.speaker.clone(), format!("Taler {ordinal}"));
        document.auto_speakers.insert(turn.speaker.clone(), ordinal);
    }
}
fn rename_speaker(document: &mut TranscriptionDocument, speaker: &str, name: &str) {
    document.speakers.insert(speaker.into(), name.into());
    document.auto_speakers.remove(speaker);
}
struct Inner {
    store: TranscriptionStore,
    documents: Vec<TranscriptionDocument>,
    cancel: BTreeMap<String, Cancellation>,
    worker: bool,
    // Derived once per source/Who result, not on every progress refresh.
    speaker_transcripts: BTreeMap<String, Transcript>,
}
pub struct Files {
    inner: Mutex<Inner>,
    root: PathBuf,
    engines: Engines,
    host: Host,
    _profile_lock: std::fs::File,
}
impl Files {
    pub fn new(host: Host, root: PathBuf) -> Result<Arc<Self>> {
        let media = root.join("transcriptions");
        std::fs::create_dir_all(&media).map_err(|e| host_io("file.directory_create", &e))?;
        let profile_lock = std::fs::OpenOptions::new()
            .read(true)
            .write(true)
            .create(true)
            .truncate(false)
            .open(root.join("transcriptions.lock"))
            .map_err(|e| host_io("file.directory_create", &e))?;
        profile_lock
            .try_lock()
            .map_err(|_| host_message("file.profile_busy"))?;
        let store =
            TranscriptionStore::open(&root.join("transcriptions.sqlite3")).map_err(|e| e.wire())?;
        let mut documents = store.all().map_err(|e| e.wire())?;
        for d in &mut documents {
            let mut changed = false;
            if let Some(plan) = &mut d.who_plan {
                if matches!(plan.stage, WhoStage::Pending | WhoStage::Running) {
                    plan.stage = WhoStage::Failed;
                    plan.error = Some(host_message("file.interrupted"));
                    changed = true;
                }
            }
            if d.stage.busy() {
                d.stage = FileStage::Failed;
                d.error = Some(host_message("file.interrupted").into());
                changed = true;
            }
            if changed {
                store.save(d).map_err(|e| e.wire())?;
            }
        }
        // Partial normalized files and cancelled/deleted job files are never replayed.
        for p in std::fs::read_dir(&media)
            .map_err(|e| host_io("file.audio_directory_read", &e))?
            .flatten()
        {
            let path = p.path();
            if path.extension().is_some_and(|e| e == "part")
                || !documents
                    .iter()
                    .any(|d| path == media.join(format!("{}.wav", d.id)))
            {
                let _ = std::fs::remove_file(path);
            }
        }
        let speaker_transcripts = documents
            .iter()
            .filter_map(|d| {
                d.diarization
                    .as_ref()
                    .zip(d.transcript.as_ref())
                    .map(|(who, t)| (d.id.clone(), who.annotate(t)))
            })
            .collect();
        let engines = Engines::new(root.join("models"))?;
        Ok(Arc::new(Self {
            inner: Mutex::new(Inner {
                store,
                documents,
                cancel: BTreeMap::new(),
                worker: false,
                speaker_transcripts,
            }),
            root: media,
            engines,
            host,
            _profile_lock: profile_lock,
        }))
    }
    fn emit(&self) {
        (self.host.notify)(None);
    }
    pub fn path(&self, id: &str) -> PathBuf {
        self.root.join(format!("{id}.wav"))
    }
    fn save(i: &mut Inner, d: TranscriptionDocument) -> Result<()> {
        i.store.save(&d).map_err(|e| e.wire())?;
        if let Some(old) = i.documents.iter_mut().find(|v| v.id == d.id) {
            *old = d;
        } else {
            i.documents.insert(0, d);
        }
        Ok(())
    }
    fn update(&self, id: &str, work: impl FnOnce(&mut TranscriptionDocument)) -> Result<()> {
        let mut i = self.inner.lock();
        let mut d = i
            .documents
            .iter()
            .find(|d| d.id == id)
            .cloned()
            .ok_or(host_message("file.transcription_missing"))?;
        work(&mut d);
        Self::save(&mut i, d)
    }
    fn update_active(
        &self,
        id: &str,
        c: &Cancellation,
        work: impl FnOnce(&mut TranscriptionDocument),
    ) -> Result<()> {
        let mut i = self.inner.lock();
        c.check()?;
        let mut d = i
            .documents
            .iter()
            .find(|d| d.id == id && d.stage.busy())
            .cloned()
            .ok_or(host_message("file.job_cancelled"))?;
        work(&mut d);
        Self::save(&mut i, d)
    }
    fn who_library(&self) -> Result<PathBuf> {
        Ok(self
            .host
            .resource_dir
            .clone()
            .ok_or(host_message("file.resource_missing"))?
            .join("runtime/who")
            .join(vara_engine::who::library_name()))
    }
    fn who_directory(&self) -> PathBuf {
        self.root.parent().unwrap().join("models/who")
    }
    pub fn document(&self, id: &str) -> Option<TranscriptionDocument> {
        self.inner
            .lock()
            .documents
            .iter()
            .find(|d| d.id == id)
            .cloned()
    }
    /// Submit one file to the same durable queue used by desktop imports.
    pub fn submit(
        self: &Arc<Self>,
        request: SubmitRequest,
        settings: &Settings,
    ) -> Result<JobReceipt> {
        let source = request
            .source
            .to_str()
            .ok_or_else(|| host_message("file.source_missing"))?;
        let ids = self.command("file_add", json!({"paths":[source], "engine":request.engine_id, "language":request.language, "request_id":request.request_id, "diarize":request.diarize, "speakers":request.speakers}), settings)?;
        let job_id = ids[0]
            .as_str()
            .ok_or_else(|| host_message("file.action_unknown"))?
            .to_owned();
        Ok(JobReceipt { job_id })
    }
    pub fn status(&self, id: &str) -> Result<TranscriptionDocument> {
        self.document(id)
            .ok_or_else(|| host_message("file.document_missing"))
    }
    pub fn result(&self, id: &str) -> Result<TranscriptionDocument> {
        let d = self.status(id)?;
        if d.stage != FileStage::Ready {
            return Err(host_message("file.not_ready"));
        }
        Ok(d)
    }
    /// Publish one document export while holding the owner lock. This is a
    /// narrow export operation, not a general filesystem write API.
    pub fn export_to(
        &self,
        id: &str,
        format: &str,
        path: &std::path::Path,
        overwrite: bool,
        original: bool,
    ) -> Result<()> {
        #[cfg(unix)]
        use std::os::unix::fs::{MetadataExt, OpenOptionsExt};
        use std::{
            fs::{self, OpenOptions},
            io::Write,
        };
        let i = self.inner.lock();
        let d = i
            .documents
            .iter()
            .find(|d| d.id == id)
            .ok_or_else(|| host_message("file.document_missing"))?;
        if d.stage != FileStage::Ready {
            return Err(host_message("file.not_ready"));
        }
        let mut value =
            serde_json::to_value(d).map_err(|e| host_json("file.export_serialize", &e))?;
        sanitize(&mut value);
        let exported: TranscriptionDocument =
            serde_json::from_value(value).map_err(|e| host_json("file.export_serialize", &e))?;
        let text = exported.export(format, original).map_err(|e| e.wire())?;
        let parent = path
            .parent()
            .filter(|p| !p.as_os_str().is_empty())
            .ok_or_else(|| host_message("file.export_save"))?;
        let parent = fs::canonicalize(parent).map_err(|e| host_io("file.export_save", &e))?;
        let profile = fs::canonicalize(self.root.parent().unwrap())
            .map_err(|e| host_io("file.export_save", &e))?;
        if parent.starts_with(&profile) {
            return Err(host_message("file.export_source"));
        }
        let target = parent.join(
            path.file_name()
                .ok_or_else(|| host_message("file.export_save"))?,
        );
        // Canonicalizing an existing target also handles case-insensitive volumes.
        let canonical_target = fs::canonicalize(&target).ok();
        // Source identity is compared against all documents known to this owner,
        // including a removed source whose parent can still be resolved.
        for document in &i.documents {
            let source = std::path::Path::new(&document.source_path);
            let canonical = fs::canonicalize(source).ok().or_else(|| {
                Some(
                    fs::canonicalize(source.parent()?)
                        .ok()?
                        .join(source.file_name()?),
                )
            });
            if canonical.as_deref() == Some(target.as_path())
                || canonical
                    .as_ref()
                    .is_some_and(|source| canonical_target.as_ref() == Some(source))
            {
                return Err(host_message("file.export_source"));
            }
        }
        match fs::symlink_metadata(&target) {
            Ok(m) => {
                if !m.is_file() || m.file_type().is_symlink() {
                    return Err(host_message("file.export_source"));
                }
                #[cfg(unix)]
                if m.nlink() != 1 {
                    return Err(host_message("file.export_source"));
                }
                if !overwrite {
                    return Err(host_message("file.export_overwrite"));
                }
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => (),
            Err(e) => return Err(host_io("file.export_save", &e)),
        }
        let temp = parent.join(format!(".vara-export-{}.tmp", uuid::Uuid::new_v4()));
        let result = (|| {
            let mut opts = OpenOptions::new();
            opts.write(true).create_new(true);
            #[cfg(unix)]
            opts.mode(0o600);
            let mut file = opts.open(&temp)?;
            file.write_all(text.as_bytes())?;
            file.sync_all()?;
            drop(file);
            if overwrite {
                fs::rename(&temp, &target)?;
            } else {
                fs::hard_link(&temp, &target)?;
                fs::remove_file(&temp)?;
            }
            Ok::<(), std::io::Error>(())
        })();
        if let Err(e) = result {
            let _ = fs::remove_file(&temp);
            return Err(host_io("file.export_save", &e));
        }
        Ok(())
    }
    pub fn cancel(self: &Arc<Self>, id: &str, settings: &Settings) -> Result<()> {
        self.command("file_cancel", json!({"id":id}), settings)
            .map(|_| ())
    }
    /// Whether accepted work still owns the queue or an auxiliary operation.
    pub fn busy(&self) -> bool {
        let inner = self.inner.lock();
        inner.worker || !inner.cancel.is_empty()
    }
    pub fn stop(&self) {
        let i = self.inner.lock();
        for c in i.cancel.values() {
            c.cancel();
        }
    }
    pub fn command(self: &Arc<Self>, action: &str, p: Value, settings: &Settings) -> Result<Value> {
        let id = || document_id(&p);
        match action {
            "file_list" => {
                let i = self.inner.lock();
                return Ok(
                    json!({"documents":i.documents.iter().map(|d| { let mut value=serde_json::to_value(d).unwrap(); value["speaker_transcript"]=i.speaker_transcripts.get(&d.id).map(|t|serde_json::to_value(t).unwrap()).unwrap_or(Value::Null); value["who_busy"]=json!(i.cancel.contains_key(&format!("who:{}",d.id))); value["ai_busy"]=json!(i.cancel.contains_key(&format!("ai:{}",d.id))); value }).collect::<Vec<_>>(),"who_download_busy":i.cancel.contains_key("who:download"),"media":i.documents.iter().filter(|d|self.path(&d.id).is_file()).map(|d|(d.id.clone(),self.path(&d.id).to_string_lossy().to_string())).collect::<BTreeMap<_,_>>()}),
                );
            }
            "file_who_status" => {
                let library = self.who_library()?;
                return Ok(vara_engine::who::run(
                    &library,
                    &self.who_directory(),
                    "status",
                    None,
                    &Cancellation::default(),
                )
                .unwrap_or_else(|e| json!({"available":false,"ready":false,"error":e})));
            }
            "file_who_cancel" => {
                let key = if p["download"] == true {
                    "who:download".to_owned()
                } else {
                    format!("who:{}", id()?)
                };
                let mut i = self.inner.lock();
                if let Some(c) = i.cancel.get(&key) {
                    c.cancel();
                }
                if p["download"] != true {
                    if let Some(mut d) = i
                        .documents
                        .iter()
                        .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                        .cloned()
                    {
                        if let Some(plan) = &mut d.who_plan {
                            if matches!(plan.stage, WhoStage::Pending | WhoStage::Running) {
                                plan.stage = WhoStage::Cancelled;
                                plan.error = None;
                                Self::save(&mut i, d)?;
                            }
                        }
                    }
                }
                drop(i);
                self.emit();
            }
            "file_who_download" | "file_who" => {
                let download = action == "file_who_download";
                if download && p["acknowledge_license"] != true {
                    return Err(host_message("file.who_license").into());
                }
                let key = if download {
                    "who:download".to_owned()
                } else {
                    format!("who:{}", id()?)
                };
                let document = if download {
                    None
                } else {
                    let i = self.inner.lock();
                    let d = i
                        .documents
                        .iter()
                        .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                        .cloned()
                        .ok_or(host_message("file.document_missing"))?;
                    if d.stage.busy() || d.transcript.is_none() {
                        return Err(host_message("file.who_wait").into());
                    }
                    Some(d)
                };
                let known_count = if download || p["known_speaker_count"].is_null() {
                    None
                } else {
                    Some(
                        p["known_speaker_count"]
                            .as_u64()
                            .filter(|n| (1..=16).contains(n))
                            .ok_or(host_message("file.who_count"))? as u32,
                    )
                };
                let cancel = Cancellation::default();
                {
                    let mut i = self.inner.lock();
                    if i.cancel.contains_key(&key) {
                        return Err(host_message("file.who_busy").into());
                    }
                    i.cancel.insert(key.clone(), cancel.clone());
                }
                self.emit();
                return self.execute_who(download, document, known_count, cancel, key, false);
            }
            "file_add" => {
                let paths: Vec<String> = serde_json::from_value(p["paths"].clone())
                    .map_err(|e| host_json("file.choose_first", &e))?;
                if paths.is_empty() || paths.len() > 100 {
                    return Err(host_message("file.choose_count").into());
                }
                let request_id = match p.get("request_id") {
                    None | Some(Value::Null) => None,
                    Some(Value::String(id)) if !id.trim().is_empty() && id.len() <= 200 => {
                        Some(id.as_str())
                    }
                    _ => return Err(host_message("file.request_invalid")),
                };
                if request_id.is_some() && paths.len() != 1 {
                    return Err(host_message("file.request_invalid"));
                }
                let diarize = p["diarize"].as_bool().unwrap_or(false);
                let speakers = if p["speakers"].is_null() {
                    None
                } else {
                    Some(
                        p["speakers"]
                            .as_u64()
                            .filter(|n| (1..=16).contains(n))
                            .ok_or_else(|| host_message("file.who_count"))?
                            as u32,
                    )
                };
                if speakers.is_some() && !diarize {
                    return Err(host_message("file.who_count"));
                }
                let language = p["language"]
                    .as_str()
                    .filter(|s| !s.is_empty())
                    .map(str::to_owned);
                let parameters = if request_id.is_some() {
                    let path = std::path::absolute(&paths[0])
                        .map_err(|e| host_io("file.source_missing", &e))?;
                    let mut identity =
                        json!({"source":path,"engine":p["engine"],"language":language});
                    if diarize {
                        identity["diarize"] = json!(true);
                        identity["speakers"] = json!(speakers);
                    }
                    Some(identity.to_string())
                } else {
                    None
                };
                // This lock serializes duplicate acceptance with publication to the one queue.
                let mut i = self.inner.lock();
                if let Some(id) = request_id {
                    if let Some((old, document_id)) = i.store.request(id).map_err(|e| e.wire())? {
                        if Some(&old) != parameters.as_ref() {
                            return Err(host_message("file.request_conflict"));
                        }
                        return Ok(json!([document_id]));
                    }
                }
                let engine = settings
                    .engines
                    .iter()
                    .find(|e| {
                        e.id == p["engine"].as_str().unwrap_or(&settings.speech_engine)
                            && e.kind == EngineKind::Speech
                    })
                    .cloned()
                    .ok_or(host_message("file.choose_speech"))?;
                if engine.provider == Provider::LocalParakeet && language.is_some() {
                    return Err(host_message("file.language_unsupported"));
                }
                if settings.strict_local && engine.locality != Locality::OnDevice {
                    return Err(host_message("file.privacy_only").into());
                }
                if engine.locality == Locality::OnDevice && !self.engines.ready(&engine.id) {
                    return Err(host_message("file.model_download").into());
                }
                // Validate the whole batch before publishing any queued jobs.
                for path in &paths {
                    if !std::fs::metadata(path).is_ok_and(|m| m.is_file()) {
                        return Err(host_message("file.source_missing").into());
                    }
                }
                let mut ids = vec![];
                let mut batch = vec![];
                for path in paths {
                    let source = std::path::absolute(&path)
                        .map_err(|e| host_io("file.source_missing", &e))?;
                    let source_path = source
                        .to_str()
                        .ok_or_else(|| host_message("file.source_missing"))?
                        .to_owned();
                    let name = source
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                        .to_string();
                    let d = TranscriptionDocument {
                        id: uuid::Uuid::new_v4().to_string(),
                        title: source
                            .file_stem()
                            .unwrap_or_default()
                            .to_string_lossy()
                            .to_string(),
                        source_name: name,
                        source_path,
                        created_at: now(),
                        engine: engine.clone(),
                        language: language.clone(),
                        stage: FileStage::Queued,
                        error: None,
                        duration: 0.,
                        completed_seconds: 0.,
                        waveform: vec![],
                        transcript: None,
                        edited_text: None,
                        revision: 0,
                        ai_text: None,
                        ai_engine: None,
                        speakers: BTreeMap::new(),
                        auto_speakers: BTreeMap::new(),
                        diarization: None,
                        diarization_error: None,
                        who_plan: diarize.then_some(WhoPlan {
                            known_speaker_count: speakers,
                            stage: WhoStage::Pending,
                            error: None,
                        }),
                    };
                    ids.push(d.id.clone());
                    batch.push(d);
                }
                i.store
                    .save_batch_with_request(&batch, request_id.zip(parameters.as_deref()))
                    .map_err(|e| e.wire())?;
                for d in batch {
                    i.cancel.insert(d.id.clone(), Cancellation::default());
                    i.documents.insert(0, d);
                }
                drop(i);
                self.kick();
                self.emit();
                return Ok(json!(ids));
            }
            "file_cancel" | "file_delete" => {
                let id = id()?;
                let mut i = self.inner.lock();
                if !i.documents.iter().any(|d| d.id == id) {
                    return Err(host_message("file.document_gone").into());
                }
                if action == "file_cancel"
                    && !i.documents.iter().any(|d| {
                        d.id == id
                            && (d.stage.busy()
                                || d.who_plan.as_ref().is_some_and(|p| {
                                    matches!(p.stage, WhoStage::Pending | WhoStage::Running)
                                }))
                    })
                {
                    return Err(host_message("file.not_processing").into());
                }
                if action == "file_delete" || action == "file_cancel" {
                    if let Some(c) = i.cancel.get(&format!("who:{id}")) {
                        c.cancel();
                    }
                }
                if action == "file_delete" {
                    if let Some(c) = i.cancel.get(&format!("ai:{id}")) {
                        c.cancel();
                    }
                }
                if let Some(c) = i.cancel.get(id) {
                    c.cancel();
                }
                if action == "file_delete" {
                    if !i.documents.iter().any(|d| d.id == id && d.stage.busy()) {
                        if let Err(error) = std::fs::remove_file(self.path(id)) {
                            if error.kind() != std::io::ErrorKind::NotFound {
                                return Err(host_io("file.audio_busy", &error));
                            }
                        }
                    }
                    i.store.delete(id).map_err(|e| e.wire())?;
                    i.documents.retain(|d| d.id != id);
                    i.speaker_transcripts.remove(id);
                } else if let Some(mut d) = i.documents.iter().find(|d| d.id == id).cloned() {
                    if d.stage.busy() {
                        d.stage = FileStage::Cancelled;
                        d.error = None;
                    }
                    if let Some(plan) = &mut d.who_plan {
                        if matches!(plan.stage, WhoStage::Pending | WhoStage::Running) {
                            plan.stage = WhoStage::Cancelled;
                            plan.error = None;
                        }
                    }
                    Self::save(&mut i, d)?;
                }
                let remove_audio = action == "file_delete"
                    || i.documents
                        .iter()
                        .find(|d| d.id == id)
                        .is_some_and(|d| d.stage == FileStage::Cancelled);
                drop(i);
                if remove_audio {
                    let _ = std::fs::remove_file(self.path(id));
                }
                self.emit();
            }
            "file_retry" => {
                let id = id()?;
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(host_message("file.gone"))?;
                if d.stage.busy() {
                    return Err(host_message("file.queued").into());
                }
                if settings.strict_local && d.engine.locality != Locality::OnDevice {
                    return Err(host_message("file.retry_cloud").into());
                }
                if d.stage == FileStage::Ready {
                    return Err(host_message("file.already_done").into());
                }
                d.stage = FileStage::Queued;
                d.error = None;
                d.completed_seconds = 0.;
                i.cancel.insert(id.into(), Cancellation::default());
                Self::save(&mut i, d)?;
                drop(i);
                self.kick();
                self.emit();
            }
            "file_persist" => {
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                    .cloned()
                    .ok_or(host_message("file.document_missing"))?;
                if d.transcript.is_none() {
                    return Err(host_message("file.no_text").into());
                }
                d.stage = FileStage::Ready;
                d.error = None;
                Self::save(&mut i, d)?;
                drop(i);
                self.emit();
            }
            "file_save" => {
                let id = id()?;
                let revision = p["revision"]
                    .as_u64()
                    .ok_or(host_message("file.revision_missing"))?;
                let text = p["text"]
                    .as_str()
                    .ok_or(host_message("file.text_missing"))?;
                if text.len() > 4_000_000 {
                    return Err(host_message("file.text_limit").into());
                }
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(host_message("file.document_missing"))?;
                if d.revision != revision {
                    return Err(host_message("file.changed_elsewhere").into());
                }
                let original = &d
                    .transcript
                    .as_ref()
                    .ok_or(host_message("file.not_ready"))?
                    .text;
                d.edited_text = if text == original {
                    None
                } else {
                    Some(text.into())
                };
                d.revision += 1;
                Self::save(&mut i, d)?;
                drop(i);
                self.emit();
                return Ok(json!({"revision":revision+1}));
            }
            "file_rename" => {
                let title = p["title"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 500)
                    .ok_or(host_message("file.title_required"))?;
                self.update(id()?, |d| d.title = title.trim().into())?;
                self.emit();
            }
            "file_ai_cancel" => {
                if let Some(c) = self.inner.lock().cancel.get(&format!("ai:{}", id()?)) {
                    c.cancel();
                }
            }
            "file_ai" => {
                let id = id()?;
                let prompt = p["prompt"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 16000)
                    .ok_or(host_message("file.instructions_required"))?;
                let engine = settings
                    .engines
                    .iter()
                    .find(|e| {
                        Some(e.id.as_str()) == p["engine"].as_str() && e.kind == EngineKind::Text
                    })
                    .cloned()
                    .ok_or(host_message("file.choose_text_model"))?;
                if settings.strict_local && engine.locality != Locality::OnDevice {
                    return Err(host_message("file.local_only").into());
                }
                let d = self
                    .inner
                    .lock()
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(host_message("file.document_missing"))?;
                if d.transcript.is_none() {
                    return Err(host_message("file.not_ready").into());
                }
                let tag = format!("ai:{id}");
                let c = Cancellation::default();
                {
                    let mut i = self.inner.lock();
                    if i.cancel.contains_key(&tag) {
                        return Err(host_message("file.ai_busy").into());
                    }
                    i.cancel.insert(tag.clone(), c.clone());
                }
                self.emit();
                let work = (|| {
                    let key = (self.host.secret)(&engine)?;
                    let plan = TextPlan {
                        engine: engine.clone(),
                        system_prompt: prompt.into(),
                        app_specific: false,
                    };
                    let output = tokio::runtime::Builder::new_current_thread()
                        .enable_all()
                        .build()
                        .map_err(|_| host_message("file.resource_missing"))?
                        .block_on(self.engines.text(&plan, d.text(), key.as_deref(), &c))?;
                    let mut i = self.inner.lock();
                    c.check()?;
                    let mut current = i
                        .documents
                        .iter()
                        .find(|v| v.id == id)
                        .cloned()
                        .ok_or(host_message("file.document_deleted"))?;
                    if current.revision != d.revision {
                        return Err(host_message("file.ai_changed").into());
                    }
                    current.ai_text = Some(output);
                    current.ai_engine = Some(engine);
                    Self::save(&mut i, current)
                })();
                self.inner.lock().cancel.remove(&tag);
                self.emit();
                work?;
            }
            "file_speaker" => {
                let speaker = p["speaker"]
                    .as_str()
                    .filter(|s| *s != "who-uncertain")
                    .ok_or(host_message("file.speaker_missing"))?;
                let name = p["name"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 200)
                    .ok_or(host_message("file.name_required"))?;
                self.update(id()?, |d| {
                    rename_speaker(d, speaker, name.trim());
                })?;
                self.emit();
            }
            _ => return Err(host_message("file.action_unknown").into()),
        }
        Ok(Value::Null)
    }
    fn execute_who(
        &self,
        download: bool,
        document: Option<TranscriptionDocument>,
        known_count: Option<u32>,
        cancel: Cancellation,
        key: String,
        planned: bool,
    ) -> Result<Value> {
        let result = (|| -> Result<Value> {
            #[cfg(feature = "test-harness")]
            if planned {
                if let Some(ms) = std::env::var("VARA_TEST_WHO_DELAY_MS")
                    .ok()
                    .and_then(|v| v.parse::<u64>().ok())
                {
                    for _ in 0..ms.min(30_000).div_ceil(10) {
                        std::thread::sleep(std::time::Duration::from_millis(10));
                        cancel.check()?;
                    }
                }
            }
            #[cfg(feature = "test-harness")]
            let fixture = if planned {
                std::env::var_os("VARA_TEST_WHO_FIXTURE")
            } else {
                None
            };
            #[cfg(not(feature = "test-harness"))]
            let fixture: Option<std::ffi::OsString> = None;
            let value = if let Some(path) = fixture {
                let data = std::fs::read(path).map_err(|e| host_io("file.who_data", &e))?;
                serde_json::from_slice(&data).map_err(|e| host_json("file.who_data", &e))?
            } else {
                let library = self.who_library()?;
                let audio = document.as_ref().map(|d| self.path(&d.id));
                vara_engine::who::run_known(
                    &library,
                    &self.who_directory(),
                    if download { "download" } else { "diarize" },
                    audio.as_deref(),
                    known_count,
                    &cancel,
                )?
            };
            if let Some(d) = &document {
                let who: Diarization = serde_json::from_value(value.clone())
                    .map_err(|e| host_json("file.who_data", &e))?;
                who.validate(d.duration).map_err(|e| e.wire())?;
                if who.turns.is_empty() {
                    return Err(host_message("file.who_unclear").into());
                }
                let annotated = who.annotate(d.transcript.as_ref().unwrap());
                let mut i = self.inner.lock();
                cancel.check()?;
                let mut current = i
                    .documents
                    .iter()
                    .find(|v| v.id == d.id)
                    .cloned()
                    .ok_or(host_message("file.document_deleted"))?;
                // Recognition retry must not receive labels from an earlier source/result.
                if current.stage != FileStage::Ready
                    || current.created_at != d.created_at
                    || current.transcript.as_ref().map(|t| &t.text)
                        != d.transcript.as_ref().map(|t| &t.text)
                {
                    return Err(host_message("file.who_changed").into());
                }
                add_who_speaker_defaults(&mut current, &who.turns);
                current.diarization = Some(who);
                current.diarization_error = None;
                if planned {
                    if let Some(plan) = &mut current.who_plan {
                        plan.stage = WhoStage::Ready;
                        plan.error = None;
                    }
                }
                cancel.publish(|| {
                    Self::save(&mut i, current)?;
                    i.speaker_transcripts.insert(d.id.clone(), annotated);
                    Ok(())
                })?;
            }
            Ok(value)
        })();
        let mut i = self.inner.lock();
        i.cancel.remove(&key);
        if let (Some(d), Err(error)) = (&document, &result) {
            if cancel.check().is_ok() {
                if let Some(mut current) = i.documents.iter().find(|v| v.id == d.id).cloned() {
                    current.diarization_error = Some(error.clone());
                    let _ = Self::save(&mut i, current);
                }
            }
        }
        if planned {
            if let Some(d) = &document {
                if let Some(mut current) = i.documents.iter().find(|v| v.id == d.id).cloned() {
                    if let Some(plan) = &mut current.who_plan {
                        if plan.stage == WhoStage::Running {
                            if cancel.check().is_err() {
                                plan.stage = WhoStage::Cancelled;
                                plan.error = None;
                            } else if let Err(error) = &result {
                                plan.stage = WhoStage::Failed;
                                plan.error = Some(error.clone());
                            }
                            let _ = Self::save(&mut i, current);
                        }
                    }
                }
            }
        }
        drop(i);
        self.emit();
        result
    }
    fn kick(self: &Arc<Self>) {
        let mut i = self.inner.lock();
        if i.worker {
            return;
        }
        i.worker = true;
        drop(i);
        let files = self.clone();
        std::thread::spawn(move || {
            match tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()
            {
                Ok(runtime) => {
                    let guard = runtime.enter();
                    files.run();
                    drop(guard);
                }
                Err(_) => {
                    let error = host_message("file.runtime_unavailable");
                    let mut i = files.inner.lock();
                    let queued: Vec<_> = i
                        .documents
                        .iter()
                        .filter(|d| d.stage == FileStage::Queued)
                        .cloned()
                        .collect();
                    for mut d in queued {
                        d.stage = FileStage::Failed;
                        d.error = Some(error.clone());
                        if let Some(plan) = &mut d.who_plan {
                            if plan.stage == WhoStage::Pending {
                                plan.stage = WhoStage::Skipped;
                            }
                        }
                        let _ = Self::save(&mut i, d);
                    }
                    i.worker = false;
                    drop(i);
                    (files.host.notify)(Some(error));
                    files.emit();
                }
            }
        });
    }
    fn run(self: Arc<Self>) {
        loop {
            let next = {
                let mut i = self.inner.lock();
                let next = i
                    .documents
                    .iter()
                    .rev()
                    .find(|d| d.stage == FileStage::Queued)
                    .cloned();
                if let Some(mut d) = next {
                    d.stage = FileStage::Decoding;
                    let c = i.cancel.entry(d.id.clone()).or_default().clone();
                    if let Err(error) = Self::save(&mut i, d.clone()) {
                        i.worker = false;
                        (self.host.notify)(Some(error));
                        return;
                    }
                    Some((d, c))
                } else {
                    i.worker = false;
                    None
                }
            };
            let Some((d, c)) = next else {
                return;
            };
            self.emit();
            let result = self.process(&d, &c);
            let _ = std::fs::remove_file(self.root.join(format!("{}.part", d.id)));
            let mut i = self.inner.lock();
            let mut who_launch = None;
            if let Some(mut current) = i.documents.iter().find(|v| v.id == d.id).cloned() {
                if c.check().is_ok() && current.stage != FileStage::Cancelled {
                    match result {
                        Ok((duration, t)) => {
                            current.stage = FileStage::Ready;
                            current.duration = duration;
                            current.completed_seconds = duration;
                            let mut names = BTreeMap::new();
                            let mut auto_names = BTreeMap::new();
                            for segment in &t.segments {
                                if let Some(speaker) = &segment.speaker {
                                    if !names.contains_key(speaker) {
                                        auto_names
                                            .insert(speaker.clone(), (names.len() + 1) as u32);
                                        names.insert(
                                            speaker.clone(),
                                            format!("Taler {}", names.len() + 1),
                                        );
                                    }
                                }
                            }
                            current.auto_speakers = auto_names;
                            current.speakers = names;
                            current.transcript = Some(t);
                            i.speaker_transcripts.remove(&current.id);
                            current.diarization = None;
                            current.diarization_error = None;
                            current.error = None;
                        }
                        Err(error) => {
                            current.stage = FileStage::Failed;
                            current.error = Some(error);
                            if let Some(plan) = &mut current.who_plan {
                                if plan.stage == WhoStage::Pending {
                                    plan.stage = WhoStage::Skipped;
                                }
                            }
                        }
                    }
                    if current.stage == FileStage::Ready {
                        if let Some(plan) = &mut current.who_plan {
                            if plan.stage == WhoStage::Pending {
                                plan.stage = WhoStage::Running;
                                let key = format!("who:{}", current.id);
                                let token = Cancellation::default();
                                who_launch = Some((key, token, plan.known_speaker_count));
                            }
                        }
                    }
                    if let Err(error) = Self::save(&mut i, current.clone()) {
                        who_launch = None;
                        current.stage = FileStage::Failed;
                        current.error = Some(host_wrapped("file.result_unsaved", &error));
                        if let Some(old) = i.documents.iter_mut().find(|v| v.id == current.id) {
                            *old = current;
                        }
                        (self.host.notify)(Some(error));
                    }
                } else {
                    let _ = std::fs::remove_file(self.path(&d.id));
                }
            } else {
                let _ = std::fs::remove_file(self.path(&d.id));
            }
            i.cancel.remove(&d.id);
            if let Some((key, token, _)) = &who_launch {
                i.cancel.insert(key.clone(), token.clone());
            }
            let who_document = who_launch
                .as_ref()
                .and_then(|_| i.documents.iter().find(|v| v.id == d.id).cloned());
            drop(i);
            self.emit();
            if let (Some((key, token, known)), Some(document)) = (who_launch, who_document) {
                let _ = self.execute_who(false, Some(document), known, token, key, true);
            }
        }
    }
    fn process(&self, d: &TranscriptionDocument, c: &Cancellation) -> Result<(f64, Transcript)> {
        let partial = self.root.join(format!("{}.part", d.id));
        let duration = if let Ok(duration) =
            vara_engine::media::normalized_duration(&self.path(&d.id))
        {
            duration
        } else {
            let duration =
                vara_engine::media::normalize(std::path::Path::new(&d.source_path), &partial, c)?;
            c.check()?;
            std::fs::rename(&partial, self.path(&d.id))
                .map_err(|e| host_io("file.audio_finalize", &e))?;
            duration
        };
        let waveform = vara_engine::media::waveform(&self.path(&d.id), c)?;
        self.update_active(&d.id, c, |d| {
            d.waveform = waveform;
            d.duration = duration;
            d.stage = FileStage::Transcribing;
        })?;
        self.emit();
        #[cfg(feature = "test-harness")]
        if let Some(path) = std::env::var_os("VARA_TEST_ASR_FIXTURE") {
            if let Some(ms) = std::env::var("VARA_TEST_ASR_DELAY_MS")
                .ok()
                .and_then(|v| v.parse::<u64>().ok())
            {
                for _ in 0..ms.min(30_000).div_ceil(10) {
                    std::thread::sleep(std::time::Duration::from_millis(10));
                    c.check()?;
                }
            }
            let data = std::fs::read(path).map_err(|e| host_io("file.source_missing", &e))?;
            let t: Transcript =
                serde_json::from_slice(&data).map_err(|e| host_json("file.who_data", &e))?;
            c.check()?;
            t.validate(duration).map_err(|e| e.wire())?;
            return Ok((duration, t));
        }
        let secret = (self.host.secret)(&d.engine)?;
        let t = self.engines.transcribe_file(
            &d.engine,
            &self.path(&d.id),
            d.language.as_deref(),
            secret.as_deref(),
            c,
            &|seconds| {
                if c.check().is_ok() {
                    let _ = self.update_active(&d.id, c, |d| d.completed_seconds = seconds);
                    self.emit();
                }
            },
        )?;
        c.check()?;
        t.validate(duration).map_err(|e| e.wire())?;
        Ok((duration, t))
    }
}

fn document_id(p: &Value) -> Result<&str> {
    p["id"]
        .as_str()
        .filter(|id| uuid::Uuid::parse_str(id).is_ok())
        .ok_or_else(|| host_message("file.id_invalid").into())
}
