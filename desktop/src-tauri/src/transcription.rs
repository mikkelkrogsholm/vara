//! Durable file jobs. Never focus, paste, or use dictation recovery/audio retention.
use parking_lot::Mutex;
use serde_json::{Value, json};
use std::{collections::BTreeMap, path::PathBuf, sync::Arc};
use tauri::{Emitter, Manager};
use vara_core::*;
use vara_engine::{Cancellation, Engines};
pub(crate) fn pick_dialog(locale: &str) -> rfd::FileDialog {
    rfd::FileDialog::new().set_title(UserMessage::new("native.file.pick").format(locale))
}
pub(crate) fn export_dialog(locale: &str, format: &str, name: &str) -> rfd::FileDialog {
    rfd::FileDialog::new().set_file_name(name).add_filter(
        &UserMessage::new("native.file.transcription").format(locale),
        &[format],
    )
}
type Result<T> = std::result::Result<T, String>;
// Track provenance only for names generated by this version. A legacy name,
// even one that looks like a default, is always treated as user content.
fn add_who_speaker_defaults(document: &mut TranscriptionDocument, turns: &[SpeakerTurn]) {
    for turn in turns {
        if turn.speaker == "who-uncertain" || document.speakers.contains_key(&turn.speaker) {
            continue;
        }
        let ordinal = turn
            .speaker
            .strip_prefix("who-")
            .and_then(|n| n.parse::<u32>().ok())
            .unwrap_or(0)
            + 1;
        document
            .speakers
            .insert(turn.speaker.clone(), format!("Taler {ordinal}"));
        document.auto_speakers.insert(turn.speaker.clone(), ordinal);
    }
}
fn rename_speaker(document: &mut TranscriptionDocument, speaker: &str, name: &str) {
    document.speakers.insert(speaker.into(), name.into());
    document.auto_speakers.remove(speaker);
}
struct Inner {
    store: TranscriptionStore,
    documents: Vec<TranscriptionDocument>,
    cancel: BTreeMap<String, Cancellation>,
    worker: bool,
    // Derived once per source/Who result, not on every progress refresh.
    speaker_transcripts: BTreeMap<String, Transcript>,
}
pub struct Files {
    inner: Mutex<Inner>,
    root: PathBuf,
    engines: Engines,
    app: tauri::AppHandle,
}
impl Files {
    pub fn new(app: tauri::AppHandle, root: PathBuf) -> Result<Arc<Self>> {
        let media = root.join("transcriptions");
        std::fs::create_dir_all(&media).map_err(|e| crate::host_io("file.directory_create", &e))?;
        let store =
            TranscriptionStore::open(&root.join("transcriptions.sqlite3")).map_err(|e| e.wire())?;
        let mut documents = store.all().map_err(|e| e.wire())?;
        for d in &mut documents {
            if d.stage.busy() {
                d.stage = FileStage::Failed;
                d.error = Some(crate::host_message("file.interrupted").into());
                store.save(d).map_err(|e| e.wire())?;
            }
        }
        // Partial normalized files and cancelled/deleted job files are never replayed.
        for p in std::fs::read_dir(&media)
            .map_err(|e| crate::host_io("file.audio_directory_read", &e))?
            .flatten()
        {
            let path = p.path();
            if path.extension().is_some_and(|e| e == "part")
                || !documents
                    .iter()
                    .any(|d| path == media.join(format!("{}.wav", d.id)))
            {
                let _ = std::fs::remove_file(path);
            }
        }
        let speaker_transcripts = documents
            .iter()
            .filter_map(|d| {
                d.diarization
                    .as_ref()
                    .zip(d.transcript.as_ref())
                    .map(|(who, t)| (d.id.clone(), who.annotate(t)))
            })
            .collect();
        let engines = Engines::new(root.join("models"))?;
        Ok(Arc::new(Self {
            inner: Mutex::new(Inner {
                store,
                documents,
                cancel: BTreeMap::new(),
                worker: false,
                speaker_transcripts,
            }),
            root: media,
            engines,
            app,
        }))
    }
    fn emit(&self) {
        let _ = self.app.emit("vara:files", ());
    }
    fn path(&self, id: &str) -> PathBuf {
        self.root.join(format!("{id}.wav"))
    }
    fn save(i: &mut Inner, d: TranscriptionDocument) -> Result<()> {
        i.store.save(&d).map_err(|e| e.wire())?;
        if let Some(old) = i.documents.iter_mut().find(|v| v.id == d.id) {
            *old = d;
        } else {
            i.documents.insert(0, d);
        }
        Ok(())
    }
    fn update(&self, id: &str, work: impl FnOnce(&mut TranscriptionDocument)) -> Result<()> {
        let mut i = self.inner.lock();
        let mut d = i
            .documents
            .iter()
            .find(|d| d.id == id)
            .cloned()
            .ok_or(crate::host_message("file.transcription_missing"))?;
        work(&mut d);
        Self::save(&mut i, d)
    }
    fn update_active(
        &self,
        id: &str,
        c: &Cancellation,
        work: impl FnOnce(&mut TranscriptionDocument),
    ) -> Result<()> {
        let mut i = self.inner.lock();
        c.check()?;
        let mut d = i
            .documents
            .iter()
            .find(|d| d.id == id && d.stage.busy())
            .cloned()
            .ok_or(crate::host_message("file.job_cancelled"))?;
        work(&mut d);
        Self::save(&mut i, d)
    }
    fn who_library(&self) -> Result<PathBuf> {
        Ok(self
            .app
            .path()
            .resource_dir()
            .map_err(|_| crate::host_message("file.resource_missing"))?
            .join("runtime/who")
            .join(vara_engine::who::library_name()))
    }
    fn who_directory(&self) -> PathBuf {
        self.root.parent().unwrap().join("models/who")
    }
    pub fn stop(&self) {
        let i = self.inner.lock();
        for c in i.cancel.values() {
            c.cancel();
        }
    }
    pub fn command(self: &Arc<Self>, action: &str, p: Value, settings: &Settings) -> Result<Value> {
        let id = || document_id(&p);
        match action {
            "file_list" => {
                let i = self.inner.lock();
                return Ok(
                    json!({"documents":i.documents.iter().map(|d| { let mut value=serde_json::to_value(d).unwrap(); value["speaker_transcript"]=i.speaker_transcripts.get(&d.id).map(|t|serde_json::to_value(t).unwrap()).unwrap_or(Value::Null); value["who_busy"]=json!(i.cancel.contains_key(&format!("who:{}",d.id))); value }).collect::<Vec<_>>(),"media":i.documents.iter().filter(|d|self.path(&d.id).is_file()).map(|d|(d.id.clone(),self.path(&d.id).to_string_lossy().to_string())).collect::<BTreeMap<_,_>>()}),
                );
            }
            "file_who_link" => {
                let url = match p["target"].as_str() {
                    Some("license") => "https://license.desertant.com/1.0",
                    Some("vendor") => "https://desertant.com",
                    _ => return Err(crate::host_message("file.who_link_unknown").into()),
                };
                #[cfg(target_os = "macos")]
                let result = std::process::Command::new("/usr/bin/open").arg(url).spawn();
                #[cfg(target_os = "windows")]
                let result = std::process::Command::new("cmd")
                    .args(["/C", "start", "", url])
                    .spawn();
                #[cfg(not(any(target_os = "macos", target_os = "windows")))]
                let result = std::process::Command::new("xdg-open").arg(url).spawn();
                result.map_err(|e| crate::host_io("file.link_open", &e))?;
            }
            "file_who_status" => {
                let library = self.who_library()?;
                return Ok(vara_engine::who::run(
                    &library,
                    &self.who_directory(),
                    "status",
                    None,
                    &Cancellation::default(),
                )
                .unwrap_or_else(|e| json!({"available":false,"ready":false,"error":e})));
            }
            "file_who_cancel" => {
                let key = if p["download"] == true {
                    "who:download".to_owned()
                } else {
                    format!("who:{}", id()?)
                };
                if let Some(c) = self.inner.lock().cancel.get(&key) {
                    c.cancel();
                }
            }
            "file_who_download" | "file_who" => {
                let download = action == "file_who_download";
                if download && p["acknowledge_license"] != true {
                    return Err(crate::host_message("file.who_license").into());
                }
                let key = if download {
                    "who:download".to_owned()
                } else {
                    format!("who:{}", id()?)
                };
                let document = if download {
                    None
                } else {
                    let i = self.inner.lock();
                    let d = i
                        .documents
                        .iter()
                        .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                        .cloned()
                        .ok_or(crate::host_message("file.document_missing"))?;
                    if d.stage.busy() || d.transcript.is_none() {
                        return Err(crate::host_message("file.who_wait").into());
                    }
                    Some(d)
                };
                let known_count = if download || p["known_speaker_count"].is_null() {
                    None
                } else {
                    Some(
                        p["known_speaker_count"]
                            .as_u64()
                            .filter(|n| (1..=16).contains(n))
                            .ok_or(crate::host_message("file.who_count"))?
                            as u32,
                    )
                };
                let cancel = Cancellation::default();
                {
                    let mut i = self.inner.lock();
                    if i.cancel.contains_key(&key) {
                        return Err(crate::host_message("file.who_busy").into());
                    }
                    i.cancel.insert(key.clone(), cancel.clone());
                }
                self.emit();
                let result = (|| -> Result<Value> {
                    let library = self.who_library()?;
                    let audio = document.as_ref().map(|d| self.path(&d.id));
                    let value = vara_engine::who::run_known(
                        &library,
                        &self.who_directory(),
                        if download { "download" } else { "diarize" },
                        audio.as_deref(),
                        known_count,
                        &cancel,
                    )?;
                    if let Some(d) = &document {
                        let who: Diarization = serde_json::from_value(value.clone())
                            .map_err(|e| crate::host_json("file.who_data", &e))?;
                        who.validate(d.duration).map_err(|e| e.wire())?;
                        if who.turns.is_empty() {
                            return Err(crate::host_message("file.who_unclear").into());
                        }
                        let annotated = who.annotate(d.transcript.as_ref().unwrap());
                        let mut i = self.inner.lock();
                        cancel.check()?;
                        let mut current = i
                            .documents
                            .iter()
                            .find(|v| v.id == d.id)
                            .cloned()
                            .ok_or(crate::host_message("file.document_deleted"))?;
                        // Recognition retry must not receive labels from an earlier source/result.
                        if current.stage != FileStage::Ready
                            || current.created_at != d.created_at
                            || current.transcript.as_ref().map(|t| &t.text)
                                != d.transcript.as_ref().map(|t| &t.text)
                        {
                            return Err(crate::host_message("file.who_changed").into());
                        }
                        add_who_speaker_defaults(&mut current, &who.turns);
                        current.diarization = Some(who);
                        current.diarization_error = None;
                        cancel.publish(|| {
                            Self::save(&mut i, current)?;
                            i.speaker_transcripts.insert(d.id.clone(), annotated);
                            Ok(())
                        })?;
                    }
                    Ok(value)
                })();
                let mut i = self.inner.lock();
                i.cancel.remove(&key);
                if let (Some(d), Err(error)) = (&document, &result) {
                    if cancel.check().is_ok() {
                        if let Some(mut current) =
                            i.documents.iter().find(|v| v.id == d.id).cloned()
                        {
                            current.diarization_error = Some(error.clone());
                            let _ = Self::save(&mut i, current);
                        }
                    }
                }
                drop(i);
                self.emit();
                return result;
            }
            "file_pick" => {
                let locale =
                    resolve_ui_locale(settings.ui_locale, &vara_platform::preferred_languages());
                let files = pick_dialog(locale).pick_files().unwrap_or_default();
                let list=files.into_iter().filter(|p|p.is_file()).map(|p|json!({"path":p.to_string_lossy(),"name":p.file_name().unwrap_or_default().to_string_lossy(),"bytes":p.metadata().map(|m|m.len()).unwrap_or(0)})).collect::<Vec<_>>();
                return Ok(json!(list));
            }
            "file_add" => {
                let paths: Vec<String> = serde_json::from_value(p["paths"].clone())
                    .map_err(|e| crate::host_json("file.choose_first", &e))?;
                if paths.is_empty() || paths.len() > 100 {
                    return Err(crate::host_message("file.choose_count").into());
                }
                let engine = settings
                    .engines
                    .iter()
                    .find(|e| {
                        Some(e.id.as_str()) == p["engine"].as_str() && e.kind == EngineKind::Speech
                    })
                    .cloned()
                    .ok_or(crate::host_message("file.choose_speech"))?;
                if settings.strict_local && engine.locality != Locality::OnDevice {
                    return Err(crate::host_message("file.privacy_only").into());
                }
                if engine.locality == Locality::OnDevice && !self.engines.ready(&engine.id) {
                    return Err(crate::host_message("file.model_download").into());
                }
                // Validate the whole batch before publishing any queued jobs.
                for path in &paths {
                    if !std::fs::metadata(path).is_ok_and(|m| m.is_file()) {
                        return Err(crate::host_message("file.source_missing").into());
                    }
                }
                let language = p["language"]
                    .as_str()
                    .filter(|s| !s.is_empty())
                    .map(str::to_owned);
                let mut i = self.inner.lock();
                let mut ids = vec![];
                let mut batch = vec![];
                for path in paths {
                    let source = PathBuf::from(&path);
                    let name = source
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                        .to_string();
                    let d = TranscriptionDocument {
                        id: uuid::Uuid::new_v4().to_string(),
                        title: source
                            .file_stem()
                            .unwrap_or_default()
                            .to_string_lossy()
                            .to_string(),
                        source_name: name,
                        source_path: path,
                        created_at: crate::service::now(),
                        engine: engine.clone(),
                        language: language.clone(),
                        stage: FileStage::Queued,
                        error: None,
                        duration: 0.,
                        completed_seconds: 0.,
                        waveform: vec![],
                        transcript: None,
                        edited_text: None,
                        revision: 0,
                        ai_text: None,
                        ai_engine: None,
                        speakers: BTreeMap::new(),
                        auto_speakers: BTreeMap::new(),
                        diarization: None,
                        diarization_error: None,
                    };
                    ids.push(d.id.clone());
                    batch.push(d);
                }
                i.store.save_batch(&batch).map_err(|e| e.wire())?;
                for d in batch {
                    i.cancel.insert(d.id.clone(), Cancellation::default());
                    i.documents.insert(0, d);
                }
                drop(i);
                self.kick();
                self.emit();
                return Ok(json!(ids));
            }
            "file_cancel" | "file_delete" => {
                let id = id()?;
                let mut i = self.inner.lock();
                if !i.documents.iter().any(|d| d.id == id) {
                    return Err(crate::host_message("file.document_gone").into());
                }
                if action == "file_cancel"
                    && !i.documents.iter().any(|d| d.id == id && d.stage.busy())
                {
                    return Err(crate::host_message("file.not_processing").into());
                }
                if action == "file_delete" {
                    if let Some(c) = i.cancel.get(&format!("who:{id}")) {
                        c.cancel();
                    }
                    if let Some(c) = i.cancel.get(&format!("ai:{id}")) {
                        c.cancel();
                    }
                }
                if let Some(c) = i.cancel.get(id) {
                    c.cancel();
                }
                if action == "file_delete" {
                    if !i.documents.iter().any(|d| d.id == id && d.stage.busy()) {
                        if let Err(error) = std::fs::remove_file(self.path(id)) {
                            if error.kind() != std::io::ErrorKind::NotFound {
                                return Err(crate::host_io("file.audio_busy", &error));
                            }
                        }
                    }
                    i.store.delete(id).map_err(|e| e.wire())?;
                    i.documents.retain(|d| d.id != id);
                    i.speaker_transcripts.remove(id);
                } else if let Some(mut d) = i.documents.iter().find(|d| d.id == id).cloned() {
                    if d.stage.busy() {
                        d.stage = FileStage::Cancelled;
                        d.error = None;
                        Self::save(&mut i, d)?;
                    }
                }
                drop(i);
                let _ = std::fs::remove_file(self.path(id));
                self.emit();
            }
            "file_retry" => {
                let id = id()?;
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(crate::host_message("file.gone"))?;
                if d.stage.busy() {
                    return Err(crate::host_message("file.queued").into());
                }
                if settings.strict_local && d.engine.locality != Locality::OnDevice {
                    return Err(crate::host_message("file.retry_cloud").into());
                }
                if d.stage == FileStage::Ready {
                    return Err(crate::host_message("file.already_done").into());
                }
                d.stage = FileStage::Queued;
                d.error = None;
                d.completed_seconds = 0.;
                i.cancel.insert(id.into(), Cancellation::default());
                Self::save(&mut i, d)?;
                drop(i);
                self.kick();
                self.emit();
            }
            "file_persist" => {
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                    .cloned()
                    .ok_or(crate::host_message("file.document_missing"))?;
                if d.transcript.is_none() {
                    return Err(crate::host_message("file.no_text").into());
                }
                d.stage = FileStage::Ready;
                d.error = None;
                Self::save(&mut i, d)?;
                drop(i);
                self.emit();
            }
            "file_save" => {
                let id = id()?;
                let revision = p["revision"]
                    .as_u64()
                    .ok_or(crate::host_message("file.revision_missing"))?;
                let text = p["text"]
                    .as_str()
                    .ok_or(crate::host_message("file.text_missing"))?;
                if text.len() > 4_000_000 {
                    return Err(crate::host_message("file.text_limit").into());
                }
                let mut i = self.inner.lock();
                let mut d = i
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(crate::host_message("file.document_missing"))?;
                if d.revision != revision {
                    return Err(crate::host_message("file.changed_elsewhere").into());
                }
                let original = &d
                    .transcript
                    .as_ref()
                    .ok_or(crate::host_message("file.not_ready"))?
                    .text;
                d.edited_text = if text == original {
                    None
                } else {
                    Some(text.into())
                };
                d.revision += 1;
                Self::save(&mut i, d)?;
                drop(i);
                self.emit();
                return Ok(json!({"revision":revision+1}));
            }
            "file_rename" => {
                let title = p["title"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 500)
                    .ok_or(crate::host_message("file.title_required"))?;
                self.update(id()?, |d| d.title = title.trim().into())?;
                self.emit();
            }
            "file_ai_cancel" => {
                if let Some(c) = self.inner.lock().cancel.get(&format!("ai:{}", id()?)) {
                    c.cancel();
                }
            }
            "file_ai" => {
                let id = id()?;
                let prompt = p["prompt"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 16000)
                    .ok_or(crate::host_message("file.instructions_required"))?;
                let engine = settings
                    .engines
                    .iter()
                    .find(|e| {
                        Some(e.id.as_str()) == p["engine"].as_str() && e.kind == EngineKind::Text
                    })
                    .cloned()
                    .ok_or(crate::host_message("file.choose_text_model"))?;
                if settings.strict_local && engine.locality != Locality::OnDevice {
                    return Err(crate::host_message("file.local_only").into());
                }
                let d = self
                    .inner
                    .lock()
                    .documents
                    .iter()
                    .find(|d| d.id == id)
                    .cloned()
                    .ok_or(crate::host_message("file.document_missing"))?;
                if d.transcript.is_none() {
                    return Err(crate::host_message("file.not_ready").into());
                }
                let tag = format!("ai:{id}");
                let c = Cancellation::default();
                {
                    let mut i = self.inner.lock();
                    if i.cancel.contains_key(&tag) {
                        return Err(crate::host_message("file.ai_busy").into());
                    }
                    i.cancel.insert(tag.clone(), c.clone());
                }
                let work = (|| {
                    let key = crate::service::engine_secret(&engine)?;
                    let plan = TextPlan {
                        engine: engine.clone(),
                        system_prompt: prompt.into(),
                        app_specific: false,
                    };
                    let output = tauri::async_runtime::block_on(self.engines.text(
                        &plan,
                        d.text(),
                        key.as_deref(),
                        &c,
                    ))?;
                    let mut i = self.inner.lock();
                    c.check()?;
                    let mut current = i
                        .documents
                        .iter()
                        .find(|v| v.id == id)
                        .cloned()
                        .ok_or(crate::host_message("file.document_deleted"))?;
                    if current.revision != d.revision {
                        return Err(crate::host_message("file.ai_changed").into());
                    }
                    current.ai_text = Some(output);
                    current.ai_engine = Some(engine);
                    Self::save(&mut i, current)
                })();
                self.inner.lock().cancel.remove(&tag);
                self.emit();
                work?;
            }
            "file_speaker" => {
                let speaker = p["speaker"]
                    .as_str()
                    .filter(|s| *s != "who-uncertain")
                    .ok_or(crate::host_message("file.speaker_missing"))?;
                let name = p["name"]
                    .as_str()
                    .filter(|s| !s.trim().is_empty() && s.len() < 200)
                    .ok_or(crate::host_message("file.name_required"))?;
                self.update(id()?, |d| {
                    rename_speaker(d, speaker, name.trim());
                })?;
                self.emit();
            }
            "file_copy" | "file_export" => {
                let mut d = self
                    .inner
                    .lock()
                    .documents
                    .iter()
                    .find(|d| Some(d.id.as_str()) == p["id"].as_str())
                    .cloned()
                    .ok_or(crate::host_message("file.document_missing"))?;
                let format = p["format"].as_str().unwrap_or("txt");
                let original = p["original"] == true;
                let unsaved_draft = !original && p["draft"].is_string();
                if unsaved_draft {
                    let text = p["draft"].as_str().unwrap();
                    if text.len() > 4_000_000 {
                        return Err(crate::host_message("file.draft_limit").into());
                    }
                    d.edited_text = Some(text.into());
                }
                let text = if p["ai"] == true {
                    let text = d
                        .ai_text
                        .clone()
                        .ok_or(crate::host_message("file.no_ai_text"))?;
                    match format {
                        "txt" => text,
                        "md" => format!("# {} — AI\n\n{}\n", d.title, text),
                        "json" => d.export("json", true).map_err(|e| e.wire())?,
                        _ => return Err(crate::host_message("file.ai_export_format").into()),
                    }
                } else {
                    d.export(format, original).map_err(|e| e.wire())?
                };
                let text = if format == "json" && unsaved_draft {
                    let mut json: Value = serde_json::from_str(&text)
                        .map_err(|e| crate::host_json("file.export_serialize", &e))?;
                    json["unsaved_draft"] = json!(true);
                    json.to_string()
                } else {
                    text
                };
                if action == "file_copy" {
                    vara_platform::copy(&text)?;
                } else {
                    let safe = d
                        .title
                        .chars()
                        .map(|c| {
                            if c.is_alphanumeric() || " -_".contains(c) {
                                c
                            } else {
                                '_'
                            }
                        })
                        .collect::<String>();
                    let locale = resolve_ui_locale(
                        settings.ui_locale,
                        &vara_platform::preferred_languages(),
                    );
                    let path =
                        export_dialog(locale, format, &format!("{safe}.{format}")).save_file();
                    if let Some(path) = path {
                        if same_file::is_same_file(&path, &d.source_path).unwrap_or(false)
                            || same_file::is_same_file(&path, self.path(&d.id)).unwrap_or(false)
                        {
                            return Err(crate::host_message("file.export_overwrite").into());
                        }
                        let target = path.canonicalize().unwrap_or(path.clone());
                        if target
                            == PathBuf::from(&d.source_path)
                                .canonicalize()
                                .unwrap_or_default()
                            || target == self.path(&d.id).canonicalize().unwrap_or_default()
                        {
                            return Err(crate::host_message("file.export_source").into());
                        }
                        std::fs::write(path, text)
                            .map_err(|e| crate::host_io("file.export_save", &e))?;
                    } else {
                        return Ok(json!(false));
                    }
                }
            }
            _ => return Err(crate::host_message("file.action_unknown").into()),
        }
        Ok(Value::Null)
    }
    fn kick(self: &Arc<Self>) {
        let mut i = self.inner.lock();
        if i.worker {
            return;
        }
        i.worker = true;
        drop(i);
        let files = self.clone();
        tauri::async_runtime::spawn_blocking(move || files.run());
    }
    fn run(self: Arc<Self>) {
        loop {
            let next = {
                let mut i = self.inner.lock();
                let next = i
                    .documents
                    .iter()
                    .rev()
                    .find(|d| d.stage == FileStage::Queued)
                    .cloned();
                if let Some(mut d) = next {
                    d.stage = FileStage::Decoding;
                    let c = i.cancel.entry(d.id.clone()).or_default().clone();
                    if let Err(error) = Self::save(&mut i, d.clone()) {
                        i.worker = false;
                        let _ = self.app.emit("vara:file-error", error);
                        return;
                    }
                    Some((d, c))
                } else {
                    i.worker = false;
                    None
                }
            };
            let Some((d, c)) = next else {
                return;
            };
            self.emit();
            let result = self.process(&d, &c);
            let _ = std::fs::remove_file(self.root.join(format!("{}.part", d.id)));
            let mut i = self.inner.lock();
            if let Some(mut current) = i.documents.iter().find(|v| v.id == d.id).cloned() {
                if c.check().is_ok() && current.stage != FileStage::Cancelled {
                    match result {
                        Ok((duration, t)) => {
                            current.stage = FileStage::Ready;
                            current.duration = duration;
                            current.completed_seconds = duration;
                            let mut names = BTreeMap::new();
                            let mut auto_names = BTreeMap::new();
                            for segment in &t.segments {
                                if let Some(speaker) = &segment.speaker {
                                    if !names.contains_key(speaker) {
                                        auto_names
                                            .insert(speaker.clone(), (names.len() + 1) as u32);
                                        names.insert(
                                            speaker.clone(),
                                            format!("Taler {}", names.len() + 1),
                                        );
                                    }
                                }
                            }
                            current.auto_speakers = auto_names;
                            current.speakers = names;
                            current.transcript = Some(t);
                            i.speaker_transcripts.remove(&current.id);
                            current.diarization = None;
                            current.diarization_error = None;
                            current.error = None;
                        }
                        Err(error) => {
                            current.stage = FileStage::Failed;
                            current.error = Some(error);
                        }
                    }
                    if let Err(error) = Self::save(&mut i, current.clone()) {
                        current.stage = FileStage::Failed;
                        current.error = Some(crate::host_wrapped("file.result_unsaved", &error));
                        if let Some(old) = i.documents.iter_mut().find(|v| v.id == current.id) {
                            *old = current;
                        }
                        let _ = self.app.emit("vara:file-error", error);
                    }
                } else {
                    let _ = std::fs::remove_file(self.path(&d.id));
                }
            } else {
                let _ = std::fs::remove_file(self.path(&d.id));
            }
            i.cancel.remove(&d.id);
            drop(i);
            self.emit();
        }
    }
    fn process(&self, d: &TranscriptionDocument, c: &Cancellation) -> Result<(f64, Transcript)> {
        let partial = self.root.join(format!("{}.part", d.id));
        let duration = if let Ok(duration) =
            vara_engine::media::normalized_duration(&self.path(&d.id))
        {
            duration
        } else {
            let duration =
                vara_engine::media::normalize(std::path::Path::new(&d.source_path), &partial, c)?;
            c.check()?;
            std::fs::rename(&partial, self.path(&d.id))
                .map_err(|e| crate::host_io("file.audio_finalize", &e))?;
            duration
        };
        let waveform = vara_engine::media::waveform(&self.path(&d.id), c)?;
        self.update_active(&d.id, c, |d| {
            d.waveform = waveform;
            d.duration = duration;
            d.stage = FileStage::Transcribing;
        })?;
        self.emit();
        let secret = crate::service::engine_secret(&d.engine)?;
        let t = self.engines.transcribe_file(
            &d.engine,
            &self.path(&d.id),
            d.language.as_deref(),
            secret.as_deref(),
            c,
            &|seconds| {
                if c.check().is_ok() {
                    let _ = self.update_active(&d.id, c, |d| d.completed_seconds = seconds);
                    self.emit();
                }
            },
        )?;
        c.check()?;
        t.validate(duration).map_err(|e| e.wire())?;
        Ok((duration, t))
    }
}

fn document_id(p: &Value) -> Result<&str> {
    p["id"]
        .as_str()
        .filter(|id| uuid::Uuid::parse_str(id).is_ok())
        .ok_or_else(|| crate::host_message("file.id_invalid").into())
}
