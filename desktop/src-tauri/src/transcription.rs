    #[test]
    fn who_defaults_preserve_legacy_names_and_rename_clears_provenance() {
        let engine = Settings::default().engines.into_iter().next().unwrap();
        let mut d = TranscriptionDocument {
            id: "fixture".into(),
            title: "Fixture".into(),
            source_name: "fixture.wav".into(),
            source_path: "/fixture.wav".into(),
            created_at: 1,
            engine,
            language: None,
            stage: FileStage::Ready,
            error: None,
            duration: 3.,
            completed_seconds: 3.,
            waveform: vec![],
            transcript: None,
            edited_text: None,
            revision: 0,
            ai_text: None,
            ai_engine: None,
            speakers: BTreeMap::from([("who-0".into(), "Taler 1".into())]),
            auto_speakers: BTreeMap::new(),
            diarization: None,
            diarization_error: None,
        };
        let turns = [
            SpeakerTurn {
                speaker: "who-0".into(),
                start: 0.,
                end: 1.,
            },
            SpeakerTurn {
                speaker: "who-1".into(),
                start: 1.,
                end: 2.,
            },
            SpeakerTurn {
                speaker: "who-uncertain".into(),
                start: 2.,
                end: 3.,
            },
        ];
        add_who_speaker_defaults(&mut d, &turns);
        assert_eq!(d.speakers["who-0"], "Taler 1");
        assert!(!d.auto_speakers.contains_key("who-0"));
        assert_eq!(d.speakers["who-1"], "Taler 2");
        assert_eq!(d.auto_speakers["who-1"], 2);
        assert!(!d.speakers.contains_key("who-uncertain"));
        rename_speaker(&mut d, "who-1", "Taler 1");
        add_who_speaker_defaults(&mut d, &turns);
        assert_eq!(d.speakers["who-1"], "Taler 1");
        assert!(!d.auto_speakers.contains_key("who-1"));
    }

